package comments;

public class Comments
{
    public static void main(String[] args)
    {
        System.out.println("// is used for single line comments");
        System.out.println("/* This is used for multi line comments */");
        System.out.println("/** This is used for documentation purpose */");
    }

    //These are valid java main methods

    /*
        public static void main(String[] args)
        public static void main(String... args)
        static public void main(String[] args)
        public static void main(String args[])
    */

    /**
     This is for documentation
     You can use for documentation purpose
     */
}
